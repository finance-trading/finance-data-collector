"""Viewer payloads: write JSON plus a ``file://`` friendly script shim.

The web viewers fetch ``data/<name>.json`` when they are served over HTTP.
Opening the same pages straight from disk (``file://``) blocks ``fetch``, so
every payload is also written as ``data/<name>.js`` assigning
``window.__FDC_DATA__[<name>]``, which the pages load through a ``<script>``
tag instead.
"""

from __future__ import annotations

import json
from pathlib import Path

GLOBAL = "__FDC_DATA__"


def write_data(name: str, payload: dict, data_dir: Path | str) -> tuple[Path, Path]:
    """Write ``<data_dir>/<name>.json`` and its ``<data_dir>/<name>.js`` shim."""
    directory = Path(data_dir)
    directory.mkdir(parents=True, exist_ok=True)
    json_path = directory / f"{name}.json"
    js_path = directory / f"{name}.js"
    body = json.dumps(payload, ensure_ascii=False, indent=1)
    json_path.write_text(body)
    js_path.write_text(
        "// generated by finance-data-collector: file:// fallback for the viewers\n"
        f"window.{GLOBAL} = window.{GLOBAL} || {{}};\n"
        f"window.{GLOBAL}[{json.dumps(name)}] = {body};\n"
    )
    return json_path, js_path
